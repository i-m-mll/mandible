import fs from "node:fs";
import path from "node:path";

import type { Db } from "./db.js";
import { getMandibleHomePath } from "./platform-paths.js";
import { operatorAllowedSignerLines } from "./protected-branch-signers.js";
import { protectedBranchNames } from "./protected-branches.js";
import { onProtectionInputsChanged } from "./protection-inputs.js";
import type { Logger } from "./types.js";

/**
 * Generated projection read by the Git reference-transaction guard
 * (`hooks/git/reference-transaction`, issue 5886596).
 *
 * The guard runs inside every Git ref update, so it must not call the daemon.
 * Mandible instead keeps two small files current under
 * `$MANDIBLE_HOME/git-guard/` (default `~/.mandible/git-guard/`):
 *
 * - `protected-refs`: a header line; a `names\t<ref>\t<ref>...` line listing
 *   every protected ref name, which lets the guard dismiss other branches with
 *   two reads; then one `<git common dir>\t<refs/heads/name>` line per
 *   protected branch of each registered repository. Keying by the resolved Git
 *   common directory makes every worktree of a repository match.
 * - `allowed_signers`: the operator credentials the `ref_update` signing rule
 *   counts (src/protected-branch-signers.ts) in ssh-keygen allowed-signers
 *   format.
 *
 * Both are derived from the protection config and the user registry; they are
 * never edited by hand and are not a second source of truth.
 */
export const PROTECTED_REFS_FILE = "protected-refs";
export const ALLOWED_SIGNERS_FILE = "allowed_signers";
const PROJECTION_HEADER = "# Mandible protected-branch guard projection v1. Generated by Mandible; do not edit.";

export function defaultProtectedBranchGuardDir(): string {
  return getMandibleHomePath("git-guard");
}

export interface ProtectedBranchGuardProjection {
  /** Sorted, de-duplicated `[commonDir, refName]` pairs. */
  protectedRefs: Array<[string, string]>;
  allowedSigners: string[];
}

/**
 * Resolve a checkout root to its canonical Git common directory using only the
 * filesystem: a normal repository's `.git` directory, a linked worktree's
 * `.git` file plus `commondir`, or a bare repository itself. Returns null when
 * the root is not a Git repository on this machine.
 */
export function resolveGitCommonDir(root: string): string | null {
  const dotGit = path.join(root, ".git");
  let gitDir: string | null = null;
  const stat = statOrNull(dotGit);
  if (stat?.isDirectory()) {
    gitDir = dotGit;
  } else if (stat?.isFile()) {
    const match = /^gitdir:\s*(.+?)\s*$/m.exec(readOrNull(dotGit) ?? "");
    if (!match) return null;
    gitDir = path.resolve(root, match[1]!);
  } else if (statOrNull(path.join(root, "HEAD"))?.isFile() && statOrNull(path.join(root, "objects"))?.isDirectory()) {
    gitDir = root;
  }
  if (!gitDir) return null;
  const commonDir = readOrNull(path.join(gitDir, "commondir"))?.trim();
  const resolved = commonDir ? path.resolve(gitDir, commonDir) : gitDir;
  try {
    return fs.realpathSync.native(resolved);
  } catch {
    return null;
  }
}

export function buildProtectedBranchGuardProjection(db: Db): ProtectedBranchGuardProjection {
  const checkouts = db
    .prepare("SELECT root, default_branch FROM ledger_project_checkouts ORDER BY root")
    .all() as Array<{ root: string; default_branch: string }>;
  const refs = new Set<string>();
  for (const checkout of checkouts) {
    const commonDir = resolveGitCommonDir(checkout.root);
    // Tabs and newlines would corrupt the line format; such paths stay unprotected.
    if (!commonDir || /[\t\n\r]/.test(commonDir)) continue;
    for (const name of protectedBranchNames(db, checkout.default_branch)) {
      if (/[\s]/.test(name)) continue;
      refs.add(`${commonDir}\trefs/heads/${name}`);
    }
  }
  return {
    protectedRefs: [...refs].sort().map((line) => line.split("\t") as [string, string]),
    allowedSigners: operatorAllowedSignerLines(db, "ref_update"),
  };
}

export function renderProtectedBranchGuardProjection(
  projection: ProtectedBranchGuardProjection,
): Record<typeof PROTECTED_REFS_FILE | typeof ALLOWED_SIGNERS_FILE, string> {
  return {
    [ALLOWED_SIGNERS_FILE]: [PROJECTION_HEADER, ...projection.allowedSigners].join("\n") + "\n",
    [PROTECTED_REFS_FILE]: [
      PROJECTION_HEADER,
      ["names", ...new Set(projection.protectedRefs.map(([, ref]) => ref).sort())].join("\t"),
      ...projection.protectedRefs.map(([commonDir, ref]) => `${commonDir}\t${ref}`),
    ].join("\n") + "\n",
  };
}

/**
 * Write the projection atomically, signers before refs, so the guard never
 * sees protected refs without the matching signer file. Unchanged files are
 * left alone. Returns true when anything was written.
 */
export function writeProtectedBranchGuardProjection(
  dir: string,
  projection: ProtectedBranchGuardProjection,
): boolean {
  const rendered = renderProtectedBranchGuardProjection(projection);
  fs.mkdirSync(dir, { recursive: true });
  let changed = false;
  for (const name of [ALLOWED_SIGNERS_FILE, PROTECTED_REFS_FILE] as const) {
    const target = path.join(dir, name);
    if (readOrNull(target) === rendered[name]) continue;
    const temp = `${target}.${process.pid}.tmp`;
    fs.writeFileSync(temp, rendered[name], { encoding: "utf8", mode: 0o644 });
    fs.renameSync(temp, target);
    changed = true;
  }
  return changed;
}

export interface ProtectedBranchGuardProjector {
  refresh(reason: string): void;
  stop(): void;
}

/**
 * Keep the guard projection current in the production daemon: once at start,
 * then after every protection-input change signal, coalesced per event-loop
 * turn. There is no polling.
 */
export function startProtectedBranchGuardProjection(options: {
  db: Db;
  logger: Logger;
  dir?: string;
}): ProtectedBranchGuardProjector {
  const dir = options.dir ?? defaultProtectedBranchGuardDir();
  let scheduled: ReturnType<typeof setImmediate> | null = null;
  const pendingReasons = new Set<string>();

  const refresh = (reason: string) => {
    try {
      const projection = buildProtectedBranchGuardProjection(options.db);
      if (writeProtectedBranchGuardProjection(dir, projection)) {
        options.logger("info", "protected_branch_guard_projection_written", {
          reason,
          dir,
          protected_refs: projection.protectedRefs.length,
          allowed_signers: projection.allowedSigners.length,
        });
      }
      if (projection.allowedSigners.length === 0) {
        options.logger("warn", "protected_branch_guard_no_operator_signers", {
          dir,
          detail: "No active operator signing credential is registered, so the Git guard refuses every protected-branch update that is not a fast-forward from its upstream.",
          fix: "mandible user setup (registers the global git user.signingkey)",
        });
      }
    } catch (error) {
      options.logger("warn", "protected_branch_guard_projection_failed", { reason, dir, error: String(error) });
    }
  };

  const unsubscribe = onProtectionInputsChanged((reason) => {
    pendingReasons.add(reason);
    if (scheduled) return;
    scheduled = setImmediate(() => {
      scheduled = null;
      const reasons = [...pendingReasons].join(",");
      pendingReasons.clear();
      refresh(reasons);
    });
  });

  refresh("startup");
  return {
    refresh,
    stop() {
      unsubscribe();
      if (scheduled) clearImmediate(scheduled);
      scheduled = null;
    },
  };
}

function statOrNull(target: string): fs.Stats | null {
  try {
    return fs.statSync(target);
  } catch {
    return null;
  }
}

function readOrNull(target: string): string | null {
  try {
    return fs.readFileSync(target, "utf8");
  } catch {
    return null;
  }
}

#!/usr/bin/env bash

set -euo pipefail

err() {
  printf '%s\n' "$*" >&2
}

repo_root="$(git rev-parse --show-toplevel 2>/dev/null)"
cd "$repo_root"

build_command="${MANDIBLE_POST_MERGE_BUILD_COMMAND:-npm run build}"
signing_key="${MANDIBLE_POST_MERGE_SIGNING_KEY:-$HOME/.ssh/id_ed25519_agents.pub}"

source_changed=false
if git rev-parse --verify --quiet HEAD^1 >/dev/null \
  && git rev-parse --verify --quiet HEAD^2 >/dev/null; then
  if git diff --name-only HEAD^1 HEAD -- \
      package.json package-lock.json tsconfig.json \
      src channel-server ui/src ui/index.html ui/esbuild.config.js \
      | grep -q .; then
    source_changed=true
  fi
else
  source_changed=true
fi

if [[ "$source_changed" != "true" ]]; then
  err "[post-merge-build] no Mandible source changes detected; skipping build"
  exit 0
fi

err "[post-merge-build] running: ${build_command}"
bash -lc "$build_command"

git add -- dist ui/dist

if git diff --cached --quiet -- dist ui/dist; then
  err "[post-merge-build] generated dist is already current"
  exit 0
fi

staged_non_dist=$(git diff --cached --name-only | grep -Ev '^(dist/|ui/dist/)' || true)
if [[ -n "$staged_non_dist" ]]; then
  err "[post-merge-build] refusing to commit non-dist staged changes:"
  printf '%s\n' "$staged_non_dist" >&2
  exit 1
fi

request_note=""
if [[ -n "${MANDIBLE_AUTH_REQUEST_ID:-}" ]]; then
  request_note="Auth request: ${MANDIBLE_AUTH_REQUEST_ID}"
fi

commit_message="build Mandible dist after auth merge"
commit_body="${commit_message}

Generated by Mandible post-merge hook.
${request_note}"

err "[post-merge-build] committing generated dist"
if [[ -f "$signing_key" ]]; then
  git -c user.signingkey="$signing_key" commit -m "$commit_body"
else
  err "[post-merge-build] agent signing key not found at ${signing_key}; using repository git config"
  git commit -m "$commit_body"
fi
